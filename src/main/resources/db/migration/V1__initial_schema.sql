CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(80) NOT NULL UNIQUE,
 display_name VARCHAR(100) NOT NULL,
 password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','TECHNICIAN','VIEWER'))
);
CREATE TABLE assets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(40) NOT NULL UNIQUE,
 name VARCHAR(120) NOT NULL,
 category VARCHAR(80) NOT NULL,
 location VARCHAR(120) NOT NULL,
 status VARCHAR(30) NOT NULL CHECK (status IN ('ACTIVE','UNDER_MAINTENANCE','RETIRED')),
 version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE work_orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_id BIGINT NOT NULL REFERENCES assets(id),
 title VARCHAR(160) NOT NULL,
 description VARCHAR(4000) NOT NULL,
 priority VARCHAR(10) NOT NULL CHECK (priority IN ('LOW','MEDIUM','HIGH')),
 status VARCHAR(20) NOT NULL CHECK (status IN ('OPEN','IN_PROGRESS','COMPLETED','CANCELLED')),
 requester_id BIGINT NOT NULL REFERENCES app_users(id),
 technician_id BIGINT REFERENCES app_users(id),
 due_date DATE,
 completion_notes VARCHAR(4000),
 completed_at TIMESTAMP WITH TIME ZONE,
 version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CHECK (status <> 'COMPLETED' OR (length(trim(completion_notes)) > 0 AND completion_notes IS NOT NULL AND completed_at IS NOT NULL))
);
CREATE TABLE order_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 work_order_id BIGINT NOT NULL REFERENCES work_orders(id),
 actor_id BIGINT NOT NULL REFERENCES app_users(id),
 kind VARCHAR(20) NOT NULL CHECK (kind IN ('STATUS','ASSIGNMENT')),
 old_value VARCHAR(160),
 new_value VARCHAR(160) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_assets_status ON assets(status);
CREATE INDEX idx_orders_asset_status ON work_orders(asset_id,status);
CREATE INDEX idx_orders_requester ON work_orders(requester_id,created_at DESC);
CREATE INDEX idx_orders_technician ON work_orders(technician_id,created_at DESC);
CREATE INDEX idx_orders_status_due ON work_orders(status,due_date);
CREATE INDEX idx_history_order ON order_history(work_order_id,id);
